/**
 * Official Traditional Chinese names for Pokémon forms.
 *
 * ## Why this module exists
 *
 * `evolution_chains.json` gives all 325 form nodes a `name_zh`, but for only
 * 127 of them is that actually Chinese — the mega and gmax rows. The other 198
 * carry the *English* name pasted back: `Rattata-Alola`, `Pikachu-Rock-Star`,
 * `Kyogre-Primal`. A zh-TW page was rendering those verbatim. The separate
 * `forms[]` array in `pokemon_data.json` is not affected: it holds 80
 * mega/gmax rows with no `name_zh` at all, and `formTitleZh()` in
 * categories.js already composes Chinese for them.
 *
 * ## Why the names come from a scraped table
 *
 * `assets/js/form-names-zh.js` is generated by `scripts/fetch_form_names.py`
 * from the official Pokédex at tw.portal-pokemon.com, keyed by base species id.
 * It is the authority because these are the site's own strings; composing our
 * own would risk wording that reads as official but is not.
 *
 * ## Why there is no shared Slugifier and no form URLs
 *
 * These are display names only. The 325 form nodes have no detail pages of their
 * own, so nothing here is ever used to build a route. Do not derive
 * a slug from a form name and do not add one to `?slug=`.
 */

