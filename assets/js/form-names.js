/** True for a string that actually contains Chinese, not a pasted-back English name. */
const isChinese = (s) => typeof s === 'string' && /[^\x00-\x7F]/.test(s);

/** The base species' own Chinese name, for composing a descriptor onto. */
const baseZh = (node) => node.base_name_zh || node.name_zh || '';

/**
 * The official Chinese name for one evolution-chain form node.
 *
 * Four tiers, in order:
 *
 *  1. A per-species override, checked first so a compound or a name that does
 *     not contain the base name survives intact.
 *  2. The base name plus a descriptor from FORM_DESCRIPTOR_ZH, but only when
 *     the portal actually lists that composed string for this species. The
 *     check is what makes this safe: the portal is not a complete form list, so
 *     a species it never mentions must not be assumed to follow the pattern,
 *     and a species it mentions with a *different* string must not be
 *     overridden by our guess.
 *  3. The node's own `name_zh` when it is genuinely Chinese. This is what keeps
 *     the 93 mega and 34 gmax rows intact, including the 9 newer Megas
 *     (10278–10284, 10306, 10308) that the portal does not list at all.
 *  4. The node's `name_zh` unchanged, which for 121 forms is the English name.
 *     That is the honest last tier: the official source has no Chinese for them
 *     and inventing wording that reads as official is worse than leaving the
 *     English the data already had.
 *
 * Never returns an empty string — an empty label is worse than a wrong-language
 * one, and the caller renders it as the node's alt text too.
 */
export function formNameZh(node) {
  if (!node) return '';
  const override = FORM_NAME_OVERRIDES[node.base_id]?.[node.qualifier];
  if (override) return override;

  const descriptor = FORM_DESCRIPTOR_ZH[node.qualifier];
  if (descriptor && isChinese(baseZh(node))) {
    const composed = `${baseZh(node)}（${descriptor}）`;
    const listed = PORTAL_FORM_NAMES[node.base_id] || [];
    if (listed.some((r) => r.nameZh === composed)) return composed;
  }

  if (isChinese(node.name_zh)) return node.name_zh;
  return node.name_zh || node.name_en || '';
}
