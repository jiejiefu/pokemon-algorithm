#!/usr/bin/env python3
"""Regenerate `assets/js/glb-index.js` from the files in `assets/glbs/`.

Why the file exists
-------------------
`model3d.html` is the only page that loads a 3D model, and a 3D model is a
different order of commitment from a sprite: a missing `.png` paints a broken
image, but a missing `.glb` makes `GLTFLoader` throw and costs a request that
also cannot be retried cheaply. Two of the two models currently on disk are the
whole set, so the page cannot assume `assets/glbs/<id>.glb` resolves.

So the page asks the index first, the same way the detail page asks
`hasShiny()` before enabling the shiny toggle -- a missing entry is the normal
case, and no failed request is ever fired to discover it.

This is a filename transcription and nothing else. Unlike the scrape-backed
generators (`extract_genus_zh.py`, `extract_type_chart.py`) it has no network
access, so a re-run after dropping a new model into `assets/glbs/` is additive
rather than a re-scrape -- the same caveat `extract_shiny_index.py` carries.

Why the id is the filename
--------------------------
The models are named after the national id (`1.glb`, `25.glb`), the same
convention `assets/images/pokemon/` and `assets/data/pokemon_data.json` already
use, so no separate mapping table is needed and `pokemon_data.json` does not
have to learn a new key. A `.glb` whose stem is not a number is ignored, and
`check_glb.mjs` asserts that nothing was silently dropped -- an unrecognised
name is a typo, not a model.

Usage
-----
    python scripts/extract_glb_index.py

Writes
------
    assets/js/glb-index.js
"""

import os

GLBS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "assets", "glbs",
)
OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "assets", "js", "glb-index.js",
)

# Recorded in the module for the same reason GENUS_SOURCE (gotcha 16) and
# TYPE_CHART_SOURCE (gotcha 11) are: the provenance of a generated file belongs
# in the file, not only in git. These were supplied by the user; there is no
# public upstream this project fetched them from, and saying so is more useful
# than inventing a URL.
SOURCE = "user-supplied GLB models named by national id; no upstream fetch"

HEADER = """// GENERATED by scripts/extract_glb_index.py -- do not edit by hand.
// Source of truth: the filenames present in `assets/glbs/`.
// {source}
//
// Exists so model3d.html can decide whether an id has a 3D model *before*
// requesting it. The roster is sparse and will stay sparse -- 2 of 1025 today,
// and most of the ones that do exist carry a single animation or none at all,
// so the viewer is built around 0/1/N clips rather than the 9-clip set that
// 1.glb happens to ship. Probing per id would fire a failed request and leave a
// console error for every one of the other 1023.
//
// A missing entry is the normal case, not a defect.
export const GLB_SOURCE = "{source}";

/** Every id that has a 3D model on disk. */
export const GLB_IDS = new Set(
  "{body}"
    .split(" ")
    .filter(Boolean)
    .map(Number)
);

/** Whether `id` has a 3D model. */
export function hasGlb(id) {{
  return GLB_IDS.has(Number(id));
}}
"""


def main():
    if not os.path.isdir(GLBS_DIR):
        raise SystemExit(
            "glb directory not found: %s\n"
            "It holds the user-supplied 3D models; create it and drop the "
            "models in before regenerating." % GLBS_DIR
        )

    ids = sorted(
        int(f[:-4])
        for f in os.listdir(GLBS_DIR)
        if f.endswith(".glb") and f[:-4].isdigit()
    )
    if not ids:
        raise SystemExit(
            "no numbered GLBs in %s -- refusing to write an empty index" % GLBS_DIR
        )

    # Surfaced rather than silently skipped: a `bulbasaur.glb` would produce a
    # correct-looking index missing an id, which is exactly the class of silent
    # gap this file exists to prevent.
    unrecognised = sorted(
        f for f in os.listdir(GLBS_DIR)
        if f.endswith(".glb") and not f[:-4].isdigit()
    )

    body = " ".join(str(i) for i in ids)
    with open(OUTPUT, "w") as fh:
        fh.write(HEADER.format(source=SOURCE, body=body))

    total = sum(
        os.path.getsize(os.path.join(GLBS_DIR, "%d.glb" % i)) for i in ids
    )
    print("wrote %s" % OUTPUT)
    print("  %d ids, %d bytes of model, index %d bytes"
          % (len(ids), total, os.path.getsize(OUTPUT)))
    if unrecognised:
        print("  WARNING: ignored non-numeric filenames: %s" % ", ".join(unrecognised))


if __name__ == "__main__":
    main()
