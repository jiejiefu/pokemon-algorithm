#!/usr/bin/env python3
"""Regenerate `assets/js/cry-index.js` from the files in `assets/cries/`.

Why the file exists
-------------------
`detail.html` used to build a cry URL against
`raw.githubusercontent.com/PokeAPI/cries/main/...` and hand it to `new Audio()`.
That is the only remote fetch left in the site, and it has three failure modes
that all collapse into the same `.catch()`: a 404, a network failure, and the
browser's autoplay policy refusing to start. The button then says 「叫聲不可用」
for a second and there is nothing to tell the three apart.

The files are on disk now, so the roster answers "which ids have a cry" the same
way `sv-index.js` answers "which ids have Scarlet/Violet artwork" -- decided
*before* the request, from a generated list, so a caller can skip cleanly and a
miss is a real fact rather than a guess.

`legacy/` is a second roster, not a second copy. It covers 1-649 only (the
generation 1-5 era recordings, 10.5 kHz mono) and is a strict id subset of
`latest/`, so `hasLegacyCry()` is a genuine predicate: an id above 649 has no
legacy cry at all and asking for one is a guaranteed 404. The gen1 cry lab
depends on that distinction, so it is modelled explicitly rather than being
papered over with a `latest`-fallback.

What this script does NOT do
----------------------------
It does not transcode, rename, or re-container anything. That is a measured
decision, not laziness -- see "The .ogg extension is a lie for 93 files" below.

The .ogg extension is a lie for 93 files
----------------------------------------
93 of the 1,351 files in `latest/` are not Ogg at all: 92 are MPEG Layer III and
one is Microsoft PCM WAV, all named `.ogg`. Only three of them are species this
site can address -- 25 (Pikachu), 808 and 809 -- and the other 90 are alternate
form cries at 10000+, so the mislabelling is mostly a fact about forms rather
than about the roster. Both counts are *measured below with soundfile on every
run*, not hardcoded, so they drop to zero on their own if upstream ever corrects
the set.

Measured in headless Chrome 154 against this site's own HTTP server: all of them
fetch (200, `Content-Type: audio/ogg`), decode via `decodeAudioData` and via
`OfflineAudioContext`, and play through an `<audio>` element. Browsers sniff the
container, so the served MIME type does not decide it. Renaming them would fix a
cosmetic inconsistency, cost a re-fetch of 25 MB, and lose the property that
these files are byte-identical to what PokeAPI/cries ships -- the same upstream
policy the Scarlet/Violet artwork follows. So they stay.

The corollary is that `canPlayType` cannot detect support here: Chrome answers
`""` for `audio/ogg; codecs="mp3"` while `latest/25.ogg` plays without complaint.
Any "can this browser play cries?" check must actually decode a file.
`cry-player.js` does that and nothing else claims to know.

Where the audio came from
-------------------------
A copy of https://github.com/PokeAPI/cries (CC0 repository licence; the audio
itself is Copyright The Pokémon Company per that repo's own LICENSE file -- the
same status as every sprite this site already uses). `CRY_SOURCE` names that
repository as the refresh source.

Usage
-----
    python scripts/extract_cry_index.py

Writes
------
    assets/js/cry-index.js
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRIES_DIR = os.path.join(ROOT, "assets", "cries")
LATEST_DIR = os.path.join(CRIES_DIR, "latest")
LEGACY_DIR = os.path.join(CRIES_DIR, "legacy")
POKEMON_DATA = os.path.join(ROOT, "assets", "data", "pokemon_data.json")
OUTPUT = os.path.join(ROOT, "assets", "js", "cry-index.js")

LATEST_PREFIX = "assets/cries/latest/"
LEGACY_PREFIX = "assets/cries/legacy/"

# Recorded in the module for the same reason SV_SOURCE and
# GENUS_SOURCE are: the provenance of a generated file belongs in the file, not
# only in git. There is no second host here -- unlike the Scarlet/Violet artwork,
# the cries repository was copied once and is refreshed from one place -- so
# unlike sv-index.js this claims no per-file origin map and none is kept.
SOURCE = "https://github.com/PokeAPI/cries"

HEADER = """// GENERATED by scripts/extract_cry_index.py -- do not edit by hand.
// Source of truth: the filenames present in `assets/cries/latest/` and
// `assets/cries/legacy/`, intersected with the ids `pokemon_data.json` knows
// about. `latest/` also holds {unclaimed} form cries this site cannot address
// (10001+ alternate forms); they are deliberately not listed, because
// `pokemon_data.json` has no field that names a form and no page ever asks
// about one.
//
// Exists so a caller can decide whether to ask for a cry *before* the request,
// rather than after a 404 -- which on this site's one remaining audio surface
// left the button saying 「叫聲不可用」 with no way to tell a missing file from a
// blocked autoplay.
//
// {have} of {total} species have a `latest` cry, and {legacy_have} of them also
// have a `legacy` one. A missing entry is a real case rather than a
// hypothetical: it is what a species added to the data tomorrow looks like
// before its audio lands. `legacy/` is not a second copy of the roster -- it is
// a strict id subset (the generation 1-5 recordings), so `hasLegacyCry()` is a
// genuine predicate and an id above 649 has none at all.
//
// {mislabelled_total} file(s) in `latest/` are not Ogg -- {mislabelled_mp3} are
// MPEG Layer III and {mislabelled_wav} is PCM WAV, all behind an `.ogg` name.
// Only {mislabelled} are species this roster can address ({mislabelled_examples});
// the other {mislabelled_forms} are 10000+ form cries. Measured by this generator
// on every run, so the counts drop to zero on their own if upstream corrects the
// set. Do not "fix" them. Browsers sniff the container, not the served MIME type:
// headless Chrome fetches, decodes and plays every one of them over HTTP with
// `Content-Type: audio/ogg`, and renaming would only cost a re-fetch and lose
// the byte-for-byte match with upstream.
//
// The corollary is that `canPlayType` is not a support probe for this site --
// Chrome answers `""` for `audio/ogg; codecs="mp3"` while `latest/25.ogg` plays.
// See `cry-player.js`, which decodes one file instead of asking.
//
// CRY_SOURCE is where this audio is refreshed from.
export const CRY_SOURCE = "{source}";
export const CRY_PATH_PREFIX = "{latest_prefix}";
export const LEGACY_CRY_PATH_PREFIX = "{legacy_prefix}";

/** Every id that has a `latest` cry on disk. */
export const CRY_IDS = new Set(
  "{latest_body}"
    .split(" ")
    .filter(Boolean)
    .map(Number)
);

/**
 * Every id that ALSO has a `legacy` cry. A strict subset of `CRY_IDS`: the
 * legacy set is the generation 1-5 recordings and stops at 649.
 */
export const LEGACY_CRY_IDS = new Set(
  "{legacy_body}"
    .split(" ")
    .filter(Boolean)
    .map(Number)
);

/** Whether `id` has a `latest` cry. */
export function hasCry(id) {{
  return CRY_IDS.has(Number(id));
}}

/** Whether `id` has a `legacy` cry. False for every id above 649. */
export function hasLegacyCry(id) {{
  return LEGACY_CRY_IDS.has(Number(id));
}}

/**
 * URL for an id's cry. Only meaningful when the matching `has*` above is true.
 *
 * `legacy: true` is honoured verbatim rather than silently falling back to
 * `latest`, for the same reason `svUrl()` has no fallback: a caller that skips
 * the check should fail loudly instead of quietly hearing the wrong recording.
 */
export function cryUrl(id, {{ legacy = false }} = {{}}) {{
  const prefix = legacy ? LEGACY_CRY_PATH_PREFIX : CRY_PATH_PREFIX;
  return `${{prefix}}${{Number(id)}}.ogg`;
}}
"""


def scan(directory):
    """Split one cries directory into (ids this site knows, ids it does not).

    Returns (known_ids, unclaimed_names, mislabelled_known, mislabelled_unclaimed).
    `mislabelled_*` are the filenames whose real container is not Ogg Vorbis --
    measured, never assumed, because the whole point of the "do not rename them"
    note above is that the counts are measurements rather than constants. The two
    lists are kept apart because the split matters: the roster only ever asks for
    `known_ids`, so 92 mislabelled form cries under 10000+ would otherwise read
    as a roster problem when they are not one.
    """
    try:
        import soundfile as sf
    except ImportError:  # pragma: no cover - the roster is still correct
        sf = None

    known, unclaimed, odd_known, odd_unclaimed = set(), [], [], []
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".ogg"):
            unclaimed.append(name)
            continue
        stem = name[:-4]
        if not stem.isdigit():
            unclaimed.append(name)
            continue
        pid = int(stem)
        is_ogg = sf is None or sf.info(os.path.join(directory, name)).format == "OGG"
        if pid in KNOWN_IDS:
            known.add(pid)
            if not is_ogg:
                odd_known.append(pid)
        else:
            unclaimed.append(name)
            if not is_ogg:
                odd_unclaimed.append(pid)
    return known, unclaimed, odd_known, odd_unclaimed


def container_counts(directory):
    """How many .ogg files in `directory` are really Ogg / MP3 / WAV.

    Reported as a total for the print summary only -- the header needs the split
    between roster ids and form ids, which `scan()` already tracks, so this only
    has to answer "of everything here, what is it".
    """
    try:
        import soundfile as sf
    except ImportError:  # pragma: no cover
        return {}
    tally = {"OGG": 0, "MP3": 0, "WAV": 0}
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".ogg"):
            continue
        fmt = sf.info(os.path.join(directory, name)).format
        tally[fmt] = tally.get(fmt, 0) + 1
    return tally


def main():
    if not os.path.isdir(LATEST_DIR) or not os.path.isdir(LEGACY_DIR):
        raise SystemExit(
            "cries directories not found: %s and %s\n"
            "They are a copy of https://github.com/PokeAPI/cries; restore them "
            "before regenerating." % (LATEST_DIR, LEGACY_DIR)
        )

    global KNOWN_IDS
    with open(POKEMON_DATA, encoding="utf-8") as fh:
        KNOWN_IDS = {entry["id"] for entry in json.load(fh)}

    latest_ids, latest_unclaimed, odd_latest, odd_latest_forms = scan(LATEST_DIR)
    legacy_ids, legacy_unclaimed, odd_legacy, odd_legacy_forms = scan(LEGACY_DIR)

    for label, ids in (("latest", latest_ids), ("legacy", legacy_ids)):
        if not ids:
            raise SystemExit(
                "no cries in the %s directory match a pokemon_data.json id -- "
                "refusing to write an empty index" % label
            )

    orphan_legacy = sorted(legacy_ids - latest_ids)
    if orphan_legacy:
        raise SystemExit(
            "legacy has %d id(s) latest does not: %s\n"
            "legacy is expected to be a strict subset of latest. Fix the "
            "directories rather than the index."
            % (len(orphan_legacy), ", ".join(str(i) for i in orphan_legacy[:8]))
        )

    mislabelled_base = [i for i in odd_latest if i <= max(KNOWN_IDS)]
    containers = container_counts(LATEST_DIR)
    body = HEADER.format(
        source=SOURCE,
        latest_prefix=LATEST_PREFIX,
        legacy_prefix=LEGACY_PREFIX,
        latest_body=" ".join(str(i) for i in sorted(latest_ids)),
        legacy_body=" ".join(str(i) for i in sorted(legacy_ids)),
        have=len(latest_ids),
        total=len(KNOWN_IDS),
        legacy_have=len(legacy_ids),
        unclaimed=len(latest_unclaimed) + len(legacy_unclaimed),
        mislabelled=len(odd_latest),
        mislabelled_examples=", ".join(str(i) for i in mislabelled_base[:3]),
        mislabelled_forms=len(odd_latest_forms),
        mislabelled_total=len(odd_latest) + len(odd_latest_forms),
        mislabelled_mp3=containers.get("MP3", 0),
        mislabelled_wav=containers.get("WAV", 0),
    )
    with open(OUTPUT, "w") as fh:
        fh.write(body)

    def dirstat(path, ids):
        return sum(os.path.getsize(os.path.join(path, "%d.ogg" % i)) for i in ids)

    print("wrote %s" % OUTPUT)
    print("  latest %d/%d ids, %.1f MB, index %d bytes"
          % (len(latest_ids), len(KNOWN_IDS),
             dirstat(LATEST_DIR, latest_ids) / 1e6, os.path.getsize(OUTPUT)))
    print("  legacy %d ids (strict subset), %.1f MB"
          % (len(legacy_ids), dirstat(LEGACY_DIR, legacy_ids) / 1e6))
    if len(latest_ids) == len(KNOWN_IDS):
        print("  complete: every species has a latest cry, so no page falls back")
    else:
        print("  %d id(s) have no cry" % (len(KNOWN_IDS) - len(latest_ids)))
    if odd_latest or odd_legacy:
        print("  note: %d latest file(s) are not Ogg (%d MP3, %d WAV) behind an "
              ".ogg name; left as upstream ships them on purpose"
              % (len(odd_latest) + len(odd_latest_forms),
                 containers.get("MP3", 0), containers.get("WAV", 0)))
        print("        %d are roster species (e.g. %s), %d are 10000+ forms"
              % (len(odd_latest),
                 ", ".join(str(i) for i in odd_latest[:8]), len(odd_latest_forms)))
    if latest_unclaimed or legacy_unclaimed:
        print("  note: %d file(s) are addressed by no pokemon_data.json id and "
              "are NOT in the roster (10001+ forms); e.g. %s"
              % (len(latest_unclaimed) + len(legacy_unclaimed),
                 ", ".join(latest_unclaimed[:8])))


KNOWN_IDS = set()

if __name__ == "__main__":
    main()