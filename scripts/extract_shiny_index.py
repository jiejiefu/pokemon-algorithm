#!/usr/bin/env python3
"""Regenerate `assets/js/shiny-index.js` from the files in `assets/images/shiny/`.

Why the file exists
-------------------
The detail page's shiny toggle used to be a CSS hue-rotate placeholder, because
no shiny artwork was on disk. It is now real artwork, and the honest way to wire
it is a `src` swap -- but a swap to a file that does not exist paints a broken
image. 24 of the 1350 referenced ids have no shiny file:

  * 8 that exist only under `assets/images/pokemon/` (the Pokeblocks and
    Pokewalker line -- PokeAPI publishes no shiny artwork for them),
  * 12 missing from both directories,
  * 4 that are the 404 nodes in chains 535/536 and have no artwork at all.

So the page has to know, before the click, whether an id has a shiny file.
Probing with `fetch` per id would fire a failed request and leave a console
error for every one of those, once per page view. A generated id list answers
the question up front for 5.7 KB.

`assets/images/shiny/` is a verbatim copy of PokeAPI's
`sprites/pokemon/other/official-artwork/shiny/{id}.png` set, so the filenames
*are* the source of truth and this script only transcribes them. It is not
byte-idempotent in the way the other generators are: it has no network access,
so a re-run after adding artwork is additive rather than a re-scrape.

Usage
-----
    python scripts/extract_shiny_index.py

Writes
------
    assets/js/shiny-index.js
"""

import os

IMAGES_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "assets", "images", "shiny",
)
OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "assets", "js", "shiny-index.js",
)

# Recorded alongside GENUS_SOURCE and TYPE_CHART_SOURCE:
# the provenance of a generated module belongs in the module, not only in git.
SOURCE = (
    "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon"
    "/other/official-artwork/shiny/{id}.png"
)

HEADER = """// GENERATED by scripts/extract_shiny_index.py -- do not edit by hand.
// Source of truth: the filenames present in `assets/images/shiny/`, which is a
// verbatim copy of PokeAPI's official-artwork shiny set.
//
// Exists so the detail page can decide whether to enable the shiny toggle
// *before* a click, rather than after a 404. 24 of the 1350 referenced ids have
// no shiny file (8 exist only under `assets/images/pokemon/` -- the Pokeblocks
// and Pokewalker line, which PokeAPI has no shiny artwork for -- 12 are missing
// from both, and 4 are the 404 nodes in chains 535/536), and probing per id
// would fire a failed request for each on every page view.
//
// A missing entry is the normal case, not a defect -- the empty states in this
// repo are meant to read that way.
export const SHINY_SOURCE = "{source}";

/** Every id that has real shiny artwork on disk. */
export const SHINY_IDS = new Set(
  "{body}"
    .split(" ")
    .map(Number)
);

/** Whether `id` has a real shiny file. */
export function hasShiny(id) {{
  return SHINY_IDS.has(Number(id));
}}
"""


def main():
    if not os.path.isdir(IMAGES_DIR):
        raise SystemExit(
            "shiny directory not found: %s\n"
            "It is a verbatim copy of PokeAPI's official-artwork shiny set; "
            "re-download it before regenerating." % IMAGES_DIR
        )

    ids = sorted(
        int(f[:-4])
        for f in os.listdir(IMAGES_DIR)
        if f.endswith(".png") and f[:-4].isdigit()
    )
    if not ids:
        raise SystemExit("no numbered PNGs in %s -- refusing to write an empty index" % IMAGES_DIR)

    body = " ".join(str(i) for i in ids)
    with open(OUTPUT, "w") as fh:
        fh.write(HEADER.format(source=SOURCE, body=body))

    print("wrote %s" % OUTPUT)
    print("  %d ids, %d bytes" % (len(ids), os.path.getsize(OUTPUT)))


if __name__ == "__main__":
    main()
