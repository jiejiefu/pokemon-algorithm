#!/usr/bin/env python3
"""Regenerate `assets/js/sv-index.js` from the files in `assets/images/scarlet-violet/`.

Why the file exists
-------------------
`types.html` lists every Pokémon of a type, and each chip shows Scarlet/Violet
artwork when it exists and the 96px `assets/images/sprite/` sprite when it does
not. That decision has to be made *before* the request, exactly like the detail
page asking `hasShiny()` before enabling the shiny toggle: pointing `src` at a
file that is not there paints a broken image. Probing per id would fire a failed
request for each miss on every type page view, and the console error is the only
trace -- the chip would otherwise look fine.

So the roster is the answer to "which ids have SV artwork", asked once.

The roster is currently *everything*: PokeAPI's generation-ix set covered only
733 of the 1025 species, and `fetch_sv_sprites.py` fills the rest from a second
source serving the same artwork (see that script for how that was verified). The
guard is still load-bearing, because it is also what a species added to the data
tomorrow hits before its art lands -- so the fallback path and the chip marking
stay in `types.html` rather than being deleted as unreachable.

Why the roster is NOT every file in the directory
------------------------------------------------
`assets/images/scarlet-violet/` holds 933 PNGs but only 733 of them are named
after a national id this project has a record for. The other 200 are:

  * 122 files at 10001-10227, and
  * 78 variant-named files (`422-east`, `493-...` Arceus forms, `666-...`
    Vivillon patterns, `669-...`/`870-...` Alcremie sweets, `585-586-season`,
    plus `female/` for Arcanine, Meowstic, Indeedee, Mastifisk and Tatsugiri).

`pokemon_data.json` has no field that addresses any of them -- `forms` is empty
for the ids sampled and the page only ever asks about species -- so transcribing
them into the roster would produce a module that looks more capable than the page
can use, and a directory that looks more covered than the site is. They are
counted and printed instead, so the day a forms mapping lands the number to beat
is written down rather than rediscovered.

This is a filename transcription and nothing else. Like `extract_shiny_index.py`
and `extract_glb_index.py` it has no network access, so a re-run after dropping
new artwork into the directory is additive rather than a re-scrape. Run
`fetch_sv_sprites.py` first to fill the directory.

Where the artwork came from
---------------------------
Per id, in `data-sources/sv-sources.json`: 733 from PokeAPI and 292 from a
fallback source that serves the same art. That map is kept outside `assets/`
because the site attributes its artwork to PokeAPI and this is repo bookkeeping,
not something the frontend should publish -- which is why the generated module
below names only PokeAPI, and why it claims no per-file origin. `SV_SOURCE` is
the refresh source, not an assertion that every file came from it.

Usage
-----
    python scripts/extract_sv_index.py

Writes
------
    assets/js/sv-index.js
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SV_DIR = os.path.join(ROOT, "assets", "images", "scarlet-violet")
POKEMON_DATA = os.path.join(ROOT, "assets", "data", "pokemon_data.json")
OUTPUT = os.path.join(ROOT, "assets", "js", "sv-index.js")

SV_PATH_PREFIX = "assets/images/scarlet-violet/"

# Recorded in the module for the same reason GENUS_SOURCE and
# TYPE_CHART_SOURCE are: the provenance of a generated file belongs
# in the file, not only in git. Kept byte-identical to SOURCES["pokeapi"] in
# fetch_sv_sprites.py -- check_sv_index.mjs asserts the two agree, because a
# fetcher that points somewhere else is how a directory loses its provenance.
#
# Only the primary is exported. The fetcher has a second source for the ids
# PokeAPI does not carry, and the site attributes its artwork to PokeAPI, so the
# per-id truth stays in data-sources/sv-sources.json rather than in a file the
# frontend loads.
SOURCE = (
    "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon"
    "/versions/generation-ix/scarlet-violet/{id}.png"
)

HEADER = """// GENERATED by scripts/extract_sv_index.py -- do not edit by hand.
// Source of truth: the filenames present in `assets/images/scarlet-violet/`,
// intersected with the ids `pokemon_data.json` knows about. The directory also
// holds {unclaimed} PNG files this site cannot address (10001-10227 plus
// variant-named forms such as `493-...` and `female/`); they are deliberately
// not listed.
//
// Exists so types.html can decide whether to ask for SV artwork *before* the
// request, rather than after a 404 -- which would leave a console error and
// nothing else to trace, on a chip that otherwise renders fine.
//
// {have} of {total} species have artwork on disk. A missing entry is a real
// case rather than a hypothetical: it is what a species added to the data looks
// like before its art lands. Callers fall back to the 96px sprite in
// `assets/images/sprite/` (which covers all {total}) and mark the chip, so a
// stand-in is never mistaken for official art.
//
// SV_SOURCE is where this artwork is refreshed from. It is not a per-file
// provenance claim: which upstream served each id is recorded in
// data-sources/sv-sources.json, which is kept outside assets/ on purpose.
export const SV_SOURCE = "{source}";
export const SV_PATH_PREFIX = "{prefix}";

/** Every id that has Scarlet/Violet artwork on disk. */
export const SV_IDS = new Set(
  "{body}"
    .split(" ")
    .filter(Boolean)
    .map(Number)
);

/** Whether `id` has Scarlet/Violet artwork. */
export function hasSv(id) {{
  return SV_IDS.has(Number(id));
}}

/**
 * URL for an id's SV artwork. Only meaningful when `hasSv(id)` is true --
 * there is deliberately no fallback here, so a caller that skips the check
 * fails loudly instead of quietly showing the wrong size of picture.
 */
export function svUrl(id) {{
  return `${{SV_PATH_PREFIX}}${{Number(id)}}.png`;
}}
"""


def main():
    if not os.path.isdir(SV_DIR):
        raise SystemExit(
            "SV directory not found: %s\n"
            "It is a copy of PokeAPI's generation-ix scarlet-violet sprite set; "
            "run fetch_sv_sprites.py or restore it before regenerating." % SV_DIR
        )

    with open(POKEMON_DATA, encoding="utf-8") as fh:
        known = {entry["id"] for entry in json.load(fh)}

    numbered, unclaimed = set(), []
    for name in sorted(os.listdir(SV_DIR)):
        path = os.path.join(SV_DIR, name)
        if os.path.isdir(path):
            # A subdirectory (female/) holds real artwork addressed by form, not
            # by id, so it never enters the roster. Its files are counted
            # individually rather than as one entry, so the number reported here
            # is a count of ARTWORK and matches the 200 quoted in the header --
            # otherwise "196" and "200" both appear in this repo for one fact.
            for sub in sorted(os.listdir(path)):
                if sub.endswith(".png"):
                    unclaimed.append("%s/%s" % (name, sub))
                else:
                    unclaimed.append("%s/%s" % (name, sub))
            continue
        if not name.endswith(".png"):
            unclaimed.append(name)
            continue
        stem = name[:-4]
        if not stem.isdigit():
            unclaimed.append(name)
            continue
        pid = int(stem)
        if pid in known:
            numbered.add(pid)
        else:
            unclaimed.append(name)

    if not numbered:
        raise SystemExit(
            "no numbered SV PNGs match a pokemon_data.json id in %s -- refusing "
            "to write an empty index" % SV_DIR
        )

    body = " ".join(str(i) for i in sorted(numbered))
    unclaimed_png = len([n for n in unclaimed if n.endswith(".png")])
    header = HEADER.format(
        source=SOURCE,
        prefix=SV_PATH_PREFIX,
        body=body,
        have=len(numbered),
        total=len(known),
        lack=len(known) - len(numbered),
        unclaimed=unclaimed_png,
    )
    with open(OUTPUT, "w") as fh:
        fh.write(header)

    total = sum(os.path.getsize(os.path.join(SV_DIR, "%d.png" % i)) for i in numbered)
    print("wrote %s" % OUTPUT)
    print("  %d of %d ids, %d bytes of artwork, index %d bytes"
          % (len(numbered), len(known), total, os.path.getsize(OUTPUT)))
    if len(numbered) == len(known):
        print("  complete: every species has SV artwork, so no chip falls back")
    else:
        print("  %d id(s) fall back to the 96px sprite: %d%%"
              % (len(known) - len(numbered),
                 round(100 * (len(known) - len(numbered)) / len(known))))
    if unclaimed:
        pngs = [n for n in unclaimed if n.endswith(".png")]
        print("  note: %d artwork file(s) in the directory are addressed by no "
              "pokemon_data.json id and are NOT in the roster (%d png, plus %d "
              "other entries)"
              % (len(unclaimed), len(pngs), len(unclaimed) - len(pngs)))
        print("        e.g. %s" % ", ".join(unclaimed[:8]))


if __name__ == "__main__":
    main()