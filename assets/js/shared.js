export function pokemonSlug(pokemon) {
  const name = pokemon?.names?.en || pokemon?.name_en || String(pokemon?.id || '');
  return name
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

