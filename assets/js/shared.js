/**
 * WCAG relative luminance / contrast. `toLinear` keeps the 0.03928 breakpoint
 * of the WCAG 1.x erratum rather than 0.04045: it is what produced the
 * measured figures recorded in AGENTS.md, and the two differ only inside a
 * ~1/255 band, so changing it would invalidate those numbers for no gain.
 */
const toLinear = v => {
  v /= 255;
  return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
};
const luminance = ([r, g, b]) => 0.2126 * toLinear(r) + 0.7152 * toLinear(g) + 0.0722 * toLinear(b);
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

/** "#a8a878" -> [168, 168, 120]. TYPE_COLORS is 6-digit hex throughout. */
export function hexToRgb(hex) {
  if (typeof hex !== 'string') return null;
  const h = hex.trim().replace('#', '');
  if (!/^[0-9a-fA-F]{6}$/.test(h)) return null;
  return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
}

/**
 * The one place a saturated fill is turned into readable text, for both the
 * Pokémon's colour swatch and the type badges. Mid-tone colours reach neither
 * 4.5:1 with white nor with near-black, so pick the better text colour and
 * then scale the fill towards black or white in 2% steps *only* until that text
 * clears 4.5:1 -- the badge still reads as the colour it represents.
 *
 * This is deliberately not a theme token. The type fills are fixed saturated
 * colours that do not change between themes, so a text colour read from the
 * theme is wrong in at least one of the two: the old `.eff-type { color:
 * var(--on-accent) }` put near-black on Fighting in dark and white on
 * Electric in light, failing both ways (3.32:1 and 1.49:1). Deriving the pair
 * from the fill is correct in every theme by construction.
 */
export function badgePair(rgb) {
  if (!Array.isArray(rgb) || rgb.length !== 3) return null;
  const LIGHT = [255, 255, 255];
  const DARK = [20, 17, 10];
  const useLightText = contrast(rgb, LIGHT) >= contrast(rgb, DARK);
  const text = useLightText ? LIGHT : DARK;
  const towards = useLightText ? [0, 0, 0] : [255, 255, 255];
  let fill = rgb.slice();
  for (let t = 0; t <= 1.0001; t += 0.02) {
    fill = rgb.map((c, i) => Math.round(c + (towards[i] - c) * t));
    if (contrast(fill, text) >= 4.5) break;
  }
  return { fill, text };
}

/**
 * The same pair as a declaration string. Split out from `badgePair` so a caller
 * that needs the two colours separately -- types.html's chart headers, which
 * hand them to CSS as custom properties rather than to `style=` -- does not have
 * to parse this back apart.
 */
export function badgeStyle(rgb) {
  const pair = badgePair(rgb);
  if (!pair) return '';
  return `background:rgb(${pair.fill.join(', ')});color:rgb(${pair.text.join(', ')})`;
}

/** The AA fill/ink pair for a type, as a fallback-tolerant lookup. */
const typeRgb = key => hexToRgb(TYPE_COLORS[key]) || [119, 119, 119];

/** The inline style for a type badge, AA-correct against its own fill. */
const typeBadgeStyle = key => badgeStyle(typeRgb(key));

/**
 * The same pair as data rather than as a declaration, for a type-coloured
 * surface that CSS paints from custom properties (types.html's chart headers).
 * Keeping the type lookup next to TYPE_COLORS is the point: a caller should
 * never re-derive the neutral fallback or the pairing rule.
 */
export function typePair(key) {
  return badgePair(typeRgb(key));
}

/**
 * Create a Pokédex card DOM element
 * @param {Object} pokemon - Pokémon data object
 * @param {Object} options - { onClick, showTypes, href, badge, shiny }
 * @returns {HTMLElement}
 *
 * `href` turns the card into an `<a>` rather than a `div`. This is the
 * difference between a card you can activate and one you can only read, and it
 * is not cosmetic: a `div` with a click handler is unreachable by keyboard and
 * invisible to assistive tech, so the category pages (`category.html`) must set
 * it rather than wiring `onClick`. A card given both is a link with a click
 * handler, which would double-fire on Enter — so `href` wins and `onClick` is
 * ignored when both are present.
 *
 * `badge` is the corner label for FORM cards (超級進化 / 超極巨化 / 阿羅亞). It
 * exists here rather than in the category page so that all nine categories share
 * one card renderer, and so the badge cannot drift out of alignment with the
 * sprite on pages that never render a plain species card.
 *
 * `shiny` points the card's `img` at `assets/images/shiny/` instead of
 * `assets/images/pokemon/`. Both directories hold the same official-artwork
 * renders at the same 475x475 and the same `{id}.png` naming, so this is a src
 * swap with no layout consequence — and it was a src swap all along: the
 * `hue-rotate` filter this option used to apply was a stand-in from when no
 * shiny file existed on disk, and it is gone (the print rule that undid it went
 * with it, so nothing could be printed believing a recolour was artwork).
 *
 * The swap is gated on `hasShiny(pokemon.id)` rather than trusting the caller:
 * `shiny-index.js` records that 24 of the 1350 ids the site references have no
 * shiny file, so a future caller passing `shiny: true` for a form id falls back
 * to the normal artwork instead of painting a broken image. A card grid cannot
 * disable anything the way the detail page's toggle can, so the fallback is the
 * whole of the empty state.
 *
 * The alt text carries 異色外觀 for the same reason the src does: a screen
 * reader has no other way to learn that the artwork in front of it is the
 * alternate palette rather than the normal one.
 */
export function createPokemonCard(pokemon, options = {}) {
  const formattedId = formatPokemonId(pokemon.id);
  const { onClick, showTypes = true, href, badge, shiny } = options;
  const name = pokemon.names?.zh || `Pokemon ${pokemon.id}`;

  const card = document.createElement(href ? 'a' : 'div');
  card.className = 'card';
  if (href) {
    card.href = href;
    // A card is a link, so it must not also read as a button to a screen reader.
    card.classList.add('card-link');
  }
  card.style.cursor = href || onClick ? 'pointer' : 'default';
  if (Array.isArray(pokemon.rgb) && pokemon.rgb.length === 3) {
    card.style.setProperty('--card-accent-rgb', pokemon.rgb.join(', '));
  }

  const useShiny = !!shiny && hasShiny(pokemon.id);
  const artwork = `${useShiny ? ASSETS.shiny : ASSETS.images}${pokemon.filename}`;

  // Types HTML
  let typesHtml = '';
  if (showTypes && pokemon.types) {
    typesHtml = `<div class="card-types" style="display:flex;gap:4px;justify-content:center;margin-top:8px;flex-wrap:wrap;">${pokemon.types.map((t, i) => typeBadgeSmHtml(t, pokemon.types_zh?.[i])).join('')}</div>`;
  }

  if (onClick && !href) {
    card.addEventListener('click', () => onClick(pokemon.id));
  }

  card.innerHTML = `
    ${badge ? `<span class="card-badge">${badge}</span>` : ''}
    <img src="${artwork}" alt="${name}${useShiny ? '（異色外觀）' : ''} #${formattedId}" loading="lazy">
    <div class="card-id">#${formattedId}</div>
    <div class="card-title">${name}</div>
    ${typesHtml}
  `;
  return card;
}

/**
 * Render Pokémon cards into a grid container
 * @param {HTMLElement} gridEl - Container element
 * @param {Array} pokemonArray - Array of Pokémon data
 */
export function renderPokemonGrid(gridEl, pokemonArray) {
  gridEl.innerHTML = '';
  const fragment = document.createDocumentFragment();

  pokemonArray.forEach(pokemon => {
    fragment.appendChild(createPokemonCard(pokemon));
  });

  gridEl.appendChild(fragment);
}

